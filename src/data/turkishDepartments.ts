export const TURKISH_DEPARTMENTS: string[] = Array.from(
  new Set(RAW_TURKISH_DEPARTMENTS)
).sort((a, b) => a.localeCompare(b, "tr-TR"));

export function searchTurkishDepartments(query: string, limit = 30): string[] {
  const clean = (query || "").trim();
  if (!clean) return TURKISH_DEPARTMENTS.slice(0, limit);

  const qLower = clean.toLocaleLowerCase("tr-TR");
  const startsWith: string[] = [];
  const contains: string[] = [];

  for (const dept of TURKISH_DEPARTMENTS) {
    const dLower = dept.toLocaleLowerCase("tr-TR");
    if (dLower.startsWith(qLower)) {
      startsWith.push(dept);
    } else if (dLower.includes(qLower)) {
      contains.push(dept);
    }
  }

  return [...startsWith, ...contains].slice(0, limit);
}
